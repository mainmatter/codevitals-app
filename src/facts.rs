//! Facts about the content of every blob either side of a change to a commit the repository
//! reaches: a `blob_fact` row per blob and language, and a `fn_fact` row per function in it.
//!
//! 1. [`missing`]: blobs without rows from this [`EXTRACTOR`].
//! 2. [`extract`] their facts.
//! 3. [`replace`] each blob's rows.
//!
//! A blob's path picks the language its content is read as, in SQL's `language()`. The content
//! alone decides the facts.

mod c;
mod python;
mod rust;
mod syntax;

use gix::ObjectId;
use sqlx::PgPool;
use tracing::instrument;

use self::syntax::CodeFacts;
use crate::{Result, changes, column, limits, mirror::Mirror};

/// Raising it extracts every blob again. Raise it whenever facts would change, a grammar upgrade
/// included.
pub const EXTRACTOR: i32 = 3;

pub async fn record(db: &PgPool, mirror: &Mirror, repo: i64) -> Result<usize> {
    let missing = missing(db, repo).await?;
    mirror
        .read_each(missing, extract, |facts| replace(db, facts))
        .await
}

// 1. Missing

/// A change's base is reached too, so both sides are in the mirror.
async fn missing(db: &PgPool, repo: i64) -> Result<Vec<(ObjectId, Option<String>)>> {
    let missing: Vec<(Vec<u8>, Option<String>)> = sqlx::query_as(
        "WITH side AS (
             SELECT ch.path, s.oid, s.mode
             FROM repo_commit r
             JOIN change ch ON ch.head = r.commit
             CROSS JOIN LATERAL (VALUES (ch.old_oid, ch.old_mode), (ch.new_oid, ch.new_mode))
                 AS s (oid, mode)
             WHERE r.repo = $1
         )
         SELECT DISTINCT oid, language(path, mode) FROM side
         WHERE mode <> 'submodule' AND NOT EXISTS (
             SELECT FROM blob_fact f
             WHERE (f.blob, f.extractor) = (side.oid, $2)
             AND f.language IS NOT DISTINCT FROM language(side.path, side.mode)
         )
         LIMIT $3",
    )
    .bind(repo)
    .bind(EXTRACTOR)
    .bind(limits::BLOBS as i64 + 1)
    .fetch_all(db)
    .await?;
    limits::check(missing.len(), limits::BLOBS, "blobs without facts")?;
    let blob = |(oid, language): (Vec<u8>, _)| (ObjectId::from_bytes_or_panic(&oid), language);
    Ok(missing.into_iter().map(blob).collect())
}

// 2. Extract

/// A `blob_fact` row and its `fn_fact` rows.
struct BlobFacts {
    blob: ObjectId,
    language: Option<String>,
    bytes: i64,
    lines: Option<i32>,
    /// Or the status saying why there are none.
    code: std::result::Result<CodeFacts, &'static str>,
}

const LFS_POINTER: &[u8] = b"version https://git-lfs.github.com/spec/";

/// Facts as far as the first status in `blob_fact.status` that applies allows.
#[instrument(level = "debug", skip_all, fields(%blob))]
fn extract(
    git: &gix::Repository,
    (blob, language): (ObjectId, Option<String>),
) -> Result<BlobFacts> {
    let size = git.find_header(blob)?.size();
    let bytes = size.try_into()?;
    let unread = |status| BlobFacts {
        blob,
        language: language.clone(),
        bytes,
        lines: None,
        code: Err(status),
    };
    if size > limits::FACT_BYTES {
        return Ok(unread("too_large"));
    }
    let content = git.find_blob(blob)?.detach().data;
    if changes::is_binary(&content) {
        return Ok(unread("binary"));
    }
    if content.starts_with(LFS_POINTER) {
        return Ok(unread("lfs_pointer"));
    }
    let lines = content.split_inclusive(|&byte| byte == b'\n').count();
    let lines = Some(lines.try_into()?);
    let code = match language.as_deref() {
        _ if is_generated(&content) => Err("generated"),
        None => Err("unsupported"),
        Some("rust") => syntax::parse(&content, &rust::RUST),
        Some("c") => syntax::parse(&content, &c::C),
        Some("cpp") => syntax::parse(&content, &c::CPP),
        Some("python") => syntax::parse(&content, &python::PYTHON),
        Some(language) => return Err(format!("no extractor for {language}").into()),
    };
    Ok(BlobFacts {
        blob,
        language,
        bytes,
        lines,
        code,
    })
}

/// What generators write in the first lines of their output, as Linguist looks for it.
const GENERATED_MARKERS: [&str; 7] = [
    "do not edit",
    "@generated",
    "auto-generated",
    "autogenerated",
    "automatically generated",
    "generated by",
    "generated with",
];

fn is_generated(content: &[u8]) -> bool {
    content.split(|&byte| byte == b'\n').take(5).any(|line| {
        let line = line.to_ascii_lowercase();
        let contains = |marker: &str| line.windows(marker.len()).any(|w| w == marker.as_bytes());
        GENERATED_MARKERS.iter().any(|marker| contains(marker))
    })
}

// 3. Replace

/// Inserting the blob's row and its functions in one statement means a sync that loses a race to
/// insert the same row adds no functions either.
async fn replace(db: &PgPool, facts: BlobFacts) -> Result {
    let (blob, language) = (facts.blob.as_slice(), facts.language.as_deref());
    let (status, code) = match &facts.code {
        Ok(code) => ("parsed", Some(code)),
        Err(status) => (*status, None),
    };
    let functions = code.map_or(&[][..], |code| &code.functions);
    let mut transaction = db.begin().await?;
    sqlx::query("DELETE FROM blob_fact WHERE blob = $1 AND language IS NOT DISTINCT FROM $2")
        .bind(blob)
        .bind(language)
        .execute(&mut *transaction)
        .await?;
    sqlx::query(
        "WITH blob_row AS (
             INSERT INTO blob_fact VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
             ON CONFLICT DO NOTHING
             RETURNING blob
         )
         INSERT INTO fn_fact
         SELECT $1, $2, f.* FROM blob_row, unnest(
             $9::text[], $10::int[], $11::int[], $12::int[], $13::int[], $14::int[], $15::int[],
             $16::bytea[], $17::bool[], $18::int[]
         ) AS f",
    )
    .bind(blob)
    .bind(language)
    .bind(EXTRACTOR)
    .bind(status)
    .bind(facts.bytes)
    .bind(facts.lines)
    .bind(code.map(|code| code.tokens))
    .bind(code.map(|code| code.errors))
    .bind(column(functions, |function| function.name.as_str()))
    .bind(column(functions, |function| function.start_line))
    .bind(column(functions, |function| function.end_line))
    .bind(column(functions, |function| function.tokens))
    .bind(column(functions, |function| function.parameters))
    .bind(column(functions, |function| function.branch_points))
    .bind(column(functions, |function| function.max_nesting))
    .bind(column(functions, |function| &function.shape[..]))
    .bind(column(functions, |function| function.test))
    .bind(column(functions, |function| function.errors))
    .execute(&mut *transaction)
    .await?;
    Ok(transaction.commit().await?)
}
